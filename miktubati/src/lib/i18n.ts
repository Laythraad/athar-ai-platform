/* Machine-generated UI dicts for the extra LANGS (build-time, committed).
   Empty/partial dicts simply fall back to English inside t(). */
import generatedLocales from "./i18n-locales/generated.json";

const generated = generatedLocales as unknown as Record<string, Dict>;

const dicts: Record<string, Dict> = {
  en,
  ar: { ...ar, ...arMission },
  ...generated,
};

/** Translate a key. Falls back to English, then to the key itself. */
export function t(lang: Lang, key: string, params?: Record<string, string | number>): string {
  let s = dicts[lang]?.[key] ?? dicts.en[key] ?? key;
  if (params) {
    for (const [k, v] of Object.entries(params)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

