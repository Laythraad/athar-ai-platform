/** Localized count with correct Arabic pluralization for works / reads. */
export function formatCount(lang: Lang, n: number, kind: "work" | "read"): string {
  if (lang === "en") {
    if (kind === "work") return n === 1 ? "1 work" : `${n} works`;
    return n === 1 ? "1 read" : `${n} reads`;
  }
  if (kind === "work") {
    if (n === 0) return "لا توجد أعمال";
    if (n === 1) return "عمل واحد";
    if (n === 2) return "عملان";
    if (n >= 3 && n <= 10) return `${n} أعمال`;
    return `${n} عملاً`;
  }
  if (n === 0) return "لا توجد قراءات";
  if (n === 1) return "قراءة واحدة";
  if (n === 2) return "قراءتان";
  if (n >= 3 && n <= 10) return `${n} قراءات`;
  return `${n} قراءة`;
}

/** Map a raw Supabase auth error message to a localized i18n key. */export function authErrorKey(message: string): string {
  const m = message.toLowerCase();
  if (m.includes("invalid login") || m.includes("invalid_credentials")) return "auth_err_invalid";
  if (m.includes("email not confirmed") || m.includes("email_not_confirmed")) return "auth_email_unverified";
  if (m.includes("already registered") || m.includes("user_already_exists") || m.includes("already been registered"))
    return "auth_err_conflict";
  if (m.includes("password should be at least") || m.includes("weak_password")) return "auth_err_weak";
  if (m.includes("failed to fetch") || m.includes("network") || m.includes("fetch failed")) return "auth_err_network";
  return "auth_err_generic";
}

/** Pick the localized side of a bilingual { en, ar } object. */
export function bl(lang: Lang, v: { en: string; ar: string } | null | undefined): string {
  if (!v) return "";
  return lang === "ar" ? v.ar || v.en : v.en || v.ar;
}

